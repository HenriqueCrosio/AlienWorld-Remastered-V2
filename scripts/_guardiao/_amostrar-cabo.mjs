// THE ROPE'S MATERIAL, SAMPLED FROM THE PAINTED CABLES (spec 2026-11-22-guardiao-coleira-design.md §9). From the root,
// after _recortar-cabos.mjs:  node scripts/_guardiao/_amostrar-cabo.mjs
// Two STRIPS of the original art, followed row by row along a near-vertical cable (the reddish one and the mossy one):
// each row is the run of opaque pixels across the cable (outline to outline), resampled to the strip's median width —
// the rope maps its arc length to a row and its cross offset to a column, so it carries the painted texture itself, not
// a profile. And the ROOTS: where the cut left a cable stump on the hull contour (erased just above, kept just below).
// Writes src/data/cordaGuardiao.ts.
import sharp from 'sharp';
import fs from 'node:fs';
import path from 'node:path';
import { yCorte } from './_recortar-cabos.mjs';

const RAIZ = path.resolve(import.meta.dirname, '../..');
const ler = async (f) => sharp(path.join(RAIZ, 'public/sprites', f)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const orig = await ler('guardiao.png');
const nova = await ler('guardiao-coleira.png');
const W = 256;
const px = (img, x, y) => { const i = (y * W + x) * 4; return [img.data[i], img.data[i + 1], img.data[i + 2], img.data[i + 3]]; };
const opaco = (img, x, y) => x >= 0 && x < W && y >= 0 && y < 256 && px(img, x, y)[3] > 128;
const hex = ([r, g, b]) => (r << 16) | (g << 8) | b;

/** follow a cable from (seedX, y0) to y1: each row's opaque run containing the previous centre */
function faixa(seedX, y0, y1) {
  const linhas = [];
  let c = seedX;
  for (let y = y0; y <= y1; y++) {
    if (!opaco(orig, c, y)) break;
    let a = c, b = c;
    while (opaco(orig, a - 1, y)) a--;
    while (opaco(orig, b + 1, y)) b++;
    linhas.push(Array.from({ length: b - a + 1 }, (_, k) => px(orig, a + k, y)));
    c = Math.round((a + b) / 2);
  }
  const larg = linhas.map((l) => l.length).sort((p, q) => p - q)[linhas.length >> 1];
  // resample every row to the median width (nearest), and drop the rows that merge with a neighbour cable
  const boas = linhas.filter((l) => Math.abs(l.length - larg) <= 2).map((l) => Array.from({ length: larg }, (_, k) => hex(l[Math.min(l.length - 1, Math.floor(((k + 0.5) * l.length) / larg))])));
  return { largura: larg, linhas: boas };
}

const FAIXAS = { ruivo: faixa(133, 0, 30), musgo: faixa(186, 0, 34) };
for (const [k, f] of Object.entries(FAIXAS)) console.log(`faixa ${k}: largura ${f.largura}, ${f.linhas.length} linhas`);

// the roots: columns where the original was opaque right above the contour and the cut art is opaque right below it
const raizes = [];
let run = null;
for (let x = 0; x < W; x++) {
  const yc = yCorte(x);
  const ok = yc > 0 && opaco(orig, x, yc - 1) && opaco(nova, x, yc);
  if (ok && run) run.x1 = x;
  else if (ok) run = { x0: x, x1: x, y: yc };
  if ((!ok || x === W - 1) && run) {
    if (run.x1 - run.x0 >= 2) raizes.push({ x: (run.x0 + run.x1) / 2 - 128, y: run.y - 128, largura: run.x1 - run.x0 + 1 });
    run = null;
  }
}
console.log(`${raizes.length} raízes:`, raizes.map((r) => `(${r.x},${r.y}) l${r.largura}`).join(' '));

// THE BACK CABLES (22/11): the cables trailing RIGHT out of the art end at the frame's right column (x=255) — at the
// station that is off screen, but at the leash stop they showed, cut on nothing. Each end becomes a rope root, PER FRAME
// of the idle sheet (the breathing moves the ends up to 4 px), with the direction the painted cable leaves in.
const sheet = await ler('guardiao-coleira-idle-sheet.png');
const opacoQ = (f, x, y) => y >= 0 && y < 256 && sheet.data[(y * sheet.info.width + x + f * 256) * 4 + 3] > 128;
const corridasCol = (f, x) => {
  const out = [];
  let ini = -1;
  for (let y = 0; y <= 256; y++) {
    const op = y < 256 && opacoQ(f, x, y);
    if (op && ini < 0) ini = y;
    if (!op && ini >= 0) {
      if (y - ini >= 3) out.push({ a: ini, b: y - 1, c: (ini + y - 1) / 2 });
      ini = -1;
    }
  }
  return out;
};
const perto = (lista, c) => lista.reduce((m, q) => (Math.abs(q.c - c) < Math.abs(m.c - c) ? q : m), lista[0]);
const NQ = sheet.info.width / 256;
const tras = corridasCol(0, 255).map((r) => {
  // the direction: the run 7 px inward nearest to this one's centre
  const dy = r.c - perto(corridasCol(0, 248), r.c).c;
  const n = Math.hypot(7, dy);
  const ys = [];
  for (let f = 0; f < NQ; f++) {
    const m = perto(corridasCol(f, 255), r.c);
    ys.push(m && Math.abs(m.c - r.c) <= 8 ? m.c - 128 : r.c - 128);
  }
  return { x: 255.5 - 128, y: ys, largura: r.b - r.a + 1, dir: { x: +(7 / n).toFixed(3), y: +(dy / n).toFixed(3) } };
});
console.log(`${tras.length} cabos de trás:`, tras.map((t) => `y${t.y[0]} l${t.largura} dir(${t.dir.x},${t.dir.y}) quadros ${t.y.join('/')}`).join('  '));

const corpo = [
  '// GENERATED by scripts/_guardiao/_amostrar-cabo.mjs — do not edit by hand.',
  '// The leash cables\' material, sampled from the painted cables of public/sprites/guardiao.png (spec',
  '// 2026-11-22-guardiao-coleira-design.md §9): two strips (rows along the cable, columns across it, 0xRRGGBB in the',
  '// PNG\'s own scale) and the roots the cut left on the hull (PNG px from the sprite centre).',
  'export interface FaixaCabo { largura: number; linhas: number[][] }',
  `export const FAIXAS_CABO: Record<'ruivo' | 'musgo', FaixaCabo> = ${JSON.stringify(FAIXAS)};`,
  `export const RAIZES_CABO: { x: number; y: number; largura: number }[] = ${JSON.stringify(raizes)};`,
  '// the back cables: where they leave the frame on the right (y per frame of the idle sheet) and the way they leave',
  `export const RAIZES_TRAS: { x: number; y: number[]; largura: number; dir: { x: number; y: number } }[] = ${JSON.stringify(tras)};`,
  '',
].join('\n');
fs.writeFileSync(path.join(RAIZ, 'src/data/cordaGuardiao.ts'), corpo);
console.log('src/data/cordaGuardiao.ts');
